#!/usr/bin/env node
// Emits src/data/mediaMeta.generated.ts from what is actually on disk.
//
// Two rules, both learned the hard way:
//   1. Discover, never enumerate. process-media.sh looped file01..fileNN and
//      silently skipped raw/file07..file12 when they landed. Anything that has
//      to be kept in step with a directory listing eventually is not.
//   2. Probe the *shipped* encode, not the raw source. `_full.mp4` is trimmed
//      (-t 12) and rescaled (scale=-2:720), so raw durations and raw pixel
//      dimensions are both wrong for anything the page displays. The aspect
//      ratio the browser lays out is the encode's, rounded-to-even width and all.
//
// A raw clip with no encode is a hard error: that is exactly the silent skip.

import { execFileSync } from 'node:child_process'
import { readdirSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const RAW = resolve(root, 'raw')
const MEDIA = resolve(root, 'public/media')
const OUT = resolve(root, 'src/data/mediaMeta.generated.ts')

/** raw/file07.mp4 -> file07. bg.mp4 is the backdrop, not an archive file. */
const ids = readdirSync(RAW)
  .filter((f) => /^file\d+\.mp4$/.test(f))
  .map((f) => f.replace(/\.mp4$/, ''))
  .sort()

if (ids.length === 0) {
  console.error('gen-media-meta: no raw/fileNN.mp4 found')
  process.exit(1)
}

const probe = (file) => {
  const out = execFileSync('ffprobe', [
    '-v', 'error',
    '-select_streams', 'v:0',
    '-show_entries', 'stream=width,height:format=duration',
    '-of', 'json',
    file,
  ]).toString()
  const json = JSON.parse(out)
  const stream = json.streams?.[0]
  const duration = Number(json.format?.duration)
  if (!stream?.width || !stream?.height || !Number.isFinite(duration)) {
    throw new Error(`ffprobe returned no usable video metadata for ${file}`)
  }
  return { width: stream.width, height: stream.height, durationSec: Math.round(duration * 100) / 100 }
}

const rows = []
for (const id of ids) {
  const full = resolve(MEDIA, `${id}_full.mp4`)
  if (!existsSync(full)) {
    console.error(`gen-media-meta: raw/${id}.mp4 has no public/media/${id}_full.mp4 — run scripts/process-media.sh`)
    process.exit(1)
  }
  const { width, height, durationSec } = probe(full)
  rows.push(`  ${id}: { width: ${width}, height: ${height}, durationSec: ${durationSec} },`)
  console.log(`${id}  ${width}x${height}  ${durationSec}s`)
}

const banner = `// GENERATED by scripts/gen-media-meta.mjs — do not edit by hand.
// Probed from public/media/*_full.mp4, the encode the page actually plays.
// Regenerate with: npm run gen:media-meta
`

writeFileSync(
  OUT,
  `${banner}
export type MediaMeta = { width: number; height: number; durationSec: number }

export const MEDIA_META: Record<string, MediaMeta> = {
${rows.join('\n')}
}
`,
)
console.log(`wrote ${OUT} (${rows.length} files)`)
