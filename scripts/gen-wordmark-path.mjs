#!/usr/bin/env node
/**
 * Turn the wordmark into outline paths, one per letter.
 *
 *   node scripts/gen-wordmark-path.mjs
 *
 * Why this exists: `createDrawable` animates a stroke along a path by its
 * length, and length comes from `getTotalLength()` — which SVG `<text>` does
 * not have, because text is not geometry. Verified in the browser before
 * writing any of this. So the letterforms have to BE paths, and the only place
 * they exist as paths is inside the font.
 *
 * Generated rather than hand-drawn, and committed rather than built at runtime:
 * opentype.js is a build-time dependency, the app ships the path data alone,
 * and nothing about the wordmark's appearance depends on a font having loaded.
 *
 * One path per letter, not one for the whole string — the draw animation
 * staggers across the letters, which needs them separable.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import opentype from 'opentype.js'

const WORD = 'SEVEREDARCHIVE'
/** Matches `.wordmark`'s CSS: Archivo Black at -0.04em tracking. */
const TRACKING_EM = -0.04
/** Any size works — the result is scaled by the viewBox. This one keeps the numbers readable. */
const SIZE = 1000

const font = opentype.parse(
  readFileSync('node_modules/@fontsource/archivo-black/files/archivo-black-latin-400-normal.woff').buffer,
)

const tracking = TRACKING_EM * SIZE
let x = 0
const letters = []

for (const char of WORD) {
  const glyph = font.charToGlyph(char)
  const path = glyph.getPath(x, 0, SIZE)
  const d = path.toPathData(2)
  if (d) letters.push(d)
  x += glyph.advanceWidth * (SIZE / font.unitsPerEm) + tracking
}

// The real ink bounds, so the viewBox hugs the letters. Deriving it from the
// font's ascender/descender instead would leave the line's leading baked in,
// and the wordmark is positioned by its glyphs, not by its line box.
const all = opentype.Path.prototype
void all
let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity
x = 0
for (const char of WORD) {
  const glyph = font.charToGlyph(char)
  const bb = glyph.getPath(x, 0, SIZE).getBoundingBox()
  if (Number.isFinite(bb.x1)) {
    minX = Math.min(minX, bb.x1); minY = Math.min(minY, bb.y1)
    maxX = Math.max(maxX, bb.x2); maxY = Math.max(maxY, bb.y2)
  }
  x += glyph.advanceWidth * (SIZE / font.unitsPerEm) + tracking
}

const width = maxX - minX
const height = maxY - minY
const out = `// GENERATED by scripts/gen-wordmark-path.mjs — do not edit by hand.
//
// The wordmark as outlines, one path per letter, so \`createDrawable\` can draw
// them: it needs \`getTotalLength()\`, which SVG <text> does not have.
//
// Regenerate if the string, the face or the tracking changes.
export const WORDMARK_TEXT = ${JSON.stringify(WORD)}
export const WORDMARK_VIEWBOX = ${JSON.stringify(`${minX.toFixed(2)} ${minY.toFixed(2)} ${width.toFixed(2)} ${height.toFixed(2)}`)}
export const WORDMARK_ASPECT = ${(width / height).toFixed(4)}
export const WORDMARK_LETTERS: readonly string[] = [
${letters.map((d) => `  ${JSON.stringify(d)},`).join('\n')}
]
`

writeFileSync('src/data/wordmark.generated.ts', out)
console.log(`wordmark: ${letters.length} letters, viewBox ${minX.toFixed(1)} ${minY.toFixed(1)} ${width.toFixed(1)} ${height.toFixed(1)}, aspect ${(width / height).toFixed(3)}`)
